-- SMARTPARK migration 001: additive integrity/index preparation.
-- Apply only after reviewing the existing data for duplicate values.

CREATE INDEX IF NOT EXISTS idx_tickets_vehicle_status
    ON bookings_and_tickets (vehicle_number, status);

CREATE INDEX IF NOT EXISTS idx_slots_status_type_distance
    ON parking_slots (status, slot_type, distance_from_entry);

CREATE INDEX IF NOT EXISTS idx_gate_logs_vehicle_timestamp
    ON gate_logs (vehicle_number, timestamp DESC);

-- Existing deployments may already have this compatibility column.
ALTER TABLE bookings_and_tickets
    ADD COLUMN IF NOT EXISTS booking_time TIMESTAMP NULL;

ALTER TABLE bookings_and_tickets
    ADD COLUMN IF NOT EXISTS qr_expires_at TIMESTAMP NULL,
    ADD COLUMN IF NOT EXISTS qr_revoked_at TIMESTAMP NULL,
    ADD COLUMN IF NOT EXISTS qr_used_at TIMESTAMP NULL;

ALTER TABLE bookings_and_tickets
    ALTER COLUMN entry_time DROP NOT NULL;

CREATE INDEX IF NOT EXISTS idx_tickets_qr_expiry
    ON bookings_and_tickets (qr_expires_at)
    WHERE status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS idx_tickets_user_created
    ON bookings_and_tickets (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS login_attempts (
    id integer generated by default as identity primary key,
    username varchar(60) not null,
    remote_address varchar(64) not null,
    window_started_at timestamp not null,
    failure_count integer not null default 0,
    unique (username, remote_address)
);
